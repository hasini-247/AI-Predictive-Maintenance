// Generates 30 historical sensor points trailing backwards
function generateHistoryPoints(
  baseTemp: number,
  baseVib: number,
  baseCurr: number,
  rpm: number,
  trend: 'stable' | 'degrading' | 'recovering' = 'stable'
): SensorReading[] {
  const points: SensorReading[] = [];
  const now = Date.now();

  for (let i = 29; i >= 0; i--) {
    const timeOffset = i * 20 * 1000; // 20s apart
    const time = new Date(now - timeOffset).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit', second: '2-digit' });

    let t = baseTemp;
    let v = baseVib;
    let c = baseCurr;

    if (trend === 'degrading') {
      const prog = (29 - i) / 29; // 0 to 1
      t = baseTemp - 8 + prog * 10;
      v = baseVib - 1.5 + prog * 2.2;
      c = baseCurr - 3 + prog * 5;
    } else if (trend === 'recovering') {
      const prog = (29 - i) / 29;
      t = baseTemp + 6 - prog * 6;
      v = baseVib + 1.2 - prog * 1.2;
    }

    // Add natural physical micro-jitter
    const noiseT = (Math.random() - 0.5) * 0.8;
    const noiseV = (Math.random() - 0.5) * 0.15;
    const noiseC = (Math.random() - 0.5) * 0.6;

    const currentTemp = Math.round((t + noiseT) * 10) / 10;
    const currentVib = Math.max(0.2, Math.round((v + noiseV) * 100) / 100);
    const currentCurr = Math.round((c + noiseC) * 10) / 10;

    const ml = runMLInference(currentTemp, currentVib, currentCurr);

    points.push({
      timestamp: time,
      temperature: currentTemp,
      vibration: currentVib,
      current: currentCurr,
      rpm: Math.round(rpm + (Math.random() - 0.5) * 15),
      anomalyScore: ml.anomalyScore,
      healthScore: ml.healthScore,
    });
  }

  return points;
}

